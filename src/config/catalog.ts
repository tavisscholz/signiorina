export function activeProducts(): Product[] {
  return products.filter((p) => p.status === "active");
}

export function getProduct(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug && p.status === "active");
}

export function getAddOn(id: string): AddOn | undefined {
  return addOns.find((a) => a.id === id);
}

export function getDietaryOption(id: string): DietaryOption | undefined {
  return dietaryOptions.find((d) => d.id === id);
}

export function productsInCategory(id: string): Product[] {
  return activeProducts().filter((p) => p.categories.includes(id as Product["categories"][number]));
}
